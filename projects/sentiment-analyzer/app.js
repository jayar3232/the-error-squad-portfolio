const {$,node,read,save}=Studio;let history=read('sentiments',[]);
for(const text of ['The setup was easy and I loved the gallery.','The gallery contains three prints.','I expected it to work, but the buttons were frustrating.','The design is lovely, but navigation is confusing.'])$('example').add(new Option(text,text));
  function render(){const list=$('history');
  list.replaceChildren(...history.map(x=>node('li',x.label+' · '+x.text)));
  if(!history.length)list.append(node('li','No reviews analyzed yet.'));
}
$('example').onchange=()=>{if($('example').value)$('review').value=$('example').value;};
  $('analyze').onclick=async()=>{const text=$('review').value.trim();
    if(!text){$('analysis').textContent='Enter some English text first.';
    $('meter').replaceChildren();
    return;
  }const r=await StudioModels.sentiment(text);
  const label=r.mixed?'Mixed signals ('+r.label.toLowerCase()+' overall)':r.label;
  $('analysis').textContent=label+' · signed score '+r.score.toFixed(2)+'. '+r.explanation;
  const bar=node('div','','signed'),fill=node('i','',r.score<0?'neg':'pos');
  fill.style.width=Math.min(1,Math.abs(r.score))*50+'%';
  bar.append(fill);
  bar.setAttribute('role','img');bar.setAttribute('aria-label','Signed score '+r.score.toFixed(2)+' on a scale from -1 to +1');
  const scale=node('div','','scale');scale.append(node('span','Negative −1'),node('span','0'),node('span','+1 Positive'));
  const badge=node('span',label,'badge '+((r.mixed||r.label==='Neutral')?'mix':r.score<0?'neg':'pos'));
  $('meter').replaceChildren(badge,bar,scale);
  history=[{label,text:text.slice(0,180)},...history].slice(0,20);
  save('sentiments',history);
  render();
};
  $('clear').onclick=()=>{$('review').value='';
  $('example').value='';
  $('analysis').textContent='';
  $('meter').replaceChildren();
};
  $('erase').onclick=()=>{history=[];
  save('sentiments',history);
  render();
};
render();
