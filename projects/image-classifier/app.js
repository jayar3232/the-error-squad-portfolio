const {$,node}=Studio;let version=0,url,ready=false;
  function reset(){version++;
  ready=false;
  const img=$('photo');
  img.onload=img.onerror=null;
  img.hidden=true;
  img.removeAttribute('src');
  if(url)URL.revokeObjectURL(url);
  url=null;
  $('file').value='';
  $('results').replaceChildren();
  $('status').textContent='Select a photo to get started.';
  $('status').classList.remove('busy');
  $('classify').disabled=true;
}
  function load(file){reset();
  if(!file)return;
    if(!['image/jpeg','image/png','image/webp'].includes(file.type)||file.size>10*1024*1024){$('status').textContent='Choose a JPEG, PNG or WebP of 10 MB or less.';
    return;
  }const img=$('photo');
    img.onload=()=>{ready=true;
    img.hidden=false;
    $('classify').disabled=false;
    $('status').textContent='Image ready for classification.';
  };
    img.onerror=()=>{$('status').textContent='This image could not be decoded.';
  };
  url=URL.createObjectURL(file);
  img.src=url;
}
$('file').onchange=e=>load(e.target.files[0]);
const drop=$('drop');
  for(const event of ['dragover','dragleave','drop'])drop.addEventListener(event,e=>{e.preventDefault();
  drop.classList.toggle('over',event==='dragover');
  if(event==='drop')load(e.dataTransfer.files[0]);
});
$('reset').onclick=reset;
  $('classify').onclick=async()=>{if(!ready)return;
  const id=version;
  $('classify').disabled=true;
  $('status').textContent='Loading MobileNet and classifying…';
  $('status').classList.add('busy');
    try{const rows=await StudioModels.classifyImage($('photo'));
    if(id!==version)return;
    const result=$('results');
    result.replaceChildren();
      rows.forEach(({label,score})=>{const bar=node('div','','bar'),fill=node('i');
      fill.style.width=score*100+'%';
      bar.append(fill);
      result.append(node('p',label+' · '+(score*100).toFixed(1)+'%'),bar);
    });
    $('status').textContent='Model output · top ImageNet classes';
    }catch(err){if(id===version)$('status').textContent=err.message+' You can explore the offline samples below.';
      }finally{if(id===version){$('classify').disabled=false;
      $('status').classList.remove('busy');
}}};
